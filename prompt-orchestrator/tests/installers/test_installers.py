def unbalanced_powershell(text: str) -> list[str]:
    """Rough delimiter check: strings, here-strings and comments are skipped."""
    problems, stack = [], []
    pairs = {")": "(", "]": "[", "}": "{"}
    i, n, line = 0, len(text), 1
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
        if text.startswith('@"', i) and text[i + 2:i + 4] in ("\r\n", "\n\r") or text.startswith('@"\n', i):
            end = text.find('\n"@', i)
            line += text.count("\n", i, end + 1)
            i = end + 3
            continue
        if c == "#" and (i == 0 or text[i - 1] in " \t\r\n;{("):
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "'":
            j = i + 1
            while j < n:
                if text[j] == "'" and text[j + 1:j + 2] == "'":
                    j += 2
                    continue
                if text[j] == "'":
                    break
                j += 1
            line += text.count("\n", i, j)
            i = j + 1
            continue
        if c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "`" else 1
            line += text.count("\n", i, j)
            i = j + 1
            continue
        if c == "`":
            i += 2
            continue
        if c in "([{":
            stack.append((c, line))
        elif c in ")]}":
            if not stack or stack[-1][0] != pairs[c]:
                problems.append(f"line {line}: unexpected {c}")
            else:
                stack.pop()
        i += 1
    problems += [f"line {ln}: unclosed {ch}" for ch, ln in stack]
    return problems


