def generate(out: Path, packs_dir: Path) -> None:
    subprocess.run([sys.executable, "-B", str(GENERATOR), "--packs-dir", str(packs_dir), "--out", str(out),
                    "--source-root", str(ROOT)], check=True, capture_output=True, text=True)


def files_under(path: Path) -> list[str]:
    return sorted(str(p.relative_to(path)) for p in path.rglob("*")) if path.exists() else []


class Sandbox:
    """A temporary HOME and a runner for one installer."""

    def __init__(self, case: unittest.TestCase, installer: Path):
        self.temporary = tempfile.TemporaryDirectory(prefix="po installer ")
        case.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name)
        self.home = self.base / "home"
        self.tmp = self.base / "tmp"
        self.home.mkdir()
        self.tmp.mkdir()
        self.installer = installer
        self.data = self.home / ".local" / "share" / "prompt-orchestrator"

    def env(self) -> dict:
        return {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(self.home), "TMPDIR": str(self.tmp),
                "LANG": "C"}

    def run(self, *args: str, stdin: str = "", ok: bool = True) -> subprocess.CompletedProcess:
        proc = subprocess.run([BASH, str(self.installer), *args], input=stdin, capture_output=True, text=True,
                              env=self.env(), timeout=600)
        if ok and proc.returncode != 0:
            raise AssertionError(f"install.sh {' '.join(args)} failed ({proc.returncode}):\n{proc.stdout}\n{proc.stderr}")
        return proc


