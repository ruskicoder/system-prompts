class ValidatorTests(unittest.TestCase):
    def test_repository_and_fixture_packs_pass(self):
        for packs_dir in (ROOT / "packs", FIXTURES):
            packs, errors = validate_packs.load_packs(packs_dir)
            self.assertEqual([], errors, packs_dir)
            self.assertTrue(packs)

    def broken(self, edit) -> list[str]:
        with tempfile.TemporaryDirectory() as tmp:
            packs_dir = Path(tmp)
            shutil.copytree(FIXTURES, packs_dir, dirs_exist_ok=True)
            edit(packs_dir)
            return validate_packs.load_packs(packs_dir)[1]

    def edit_json(self, path: Path, change) -> None:
        data = json.loads(path.read_text())
        change(data)
        path.write_text(json.dumps(data))

    def test_skill_outside_every_set_fails(self):
        def edit(d):
            self.edit_json(d / "fixture-skills" / "pack.json", lambda p: p["sets"].pop())
        self.assertTrue(any("fixture-three belongs to no set" in e for e in self.broken(edit)))

    def test_skill_in_two_sets_fails(self):
        def edit(d):
            self.edit_json(d / "fixture-skills" / "pack.json", lambda p: p["sets"][1]["skills"].append("fixture-one"))
        self.assertTrue(any("is in set alpha and set beta" in e for e in self.broken(edit)))

    def test_name_mismatch_and_long_description_fail(self):
        def edit(d):
            md = d / "fixture-skills" / "skills" / "fixture-one" / "SKILL.md"
            md.write_text(md.read_text().replace("name: fixture-one", "name: other-name")
                          .replace("description: Fixture", "description: " + "x" * 1100))
        errors = self.broken(edit)
        self.assertTrue(any("differs from the folder name" in e for e in errors))
        self.assertTrue(any("limit 1024" in e for e in errors))

    def test_schema_keys_fail(self):
        def edit(d):
            self.edit_json(d / "fixture-skills" / "pack.json", lambda p: (p.pop("license"), p.update(extra=1)))
        errors = self.broken(edit)
        self.assertTrue(any("misses key 'license'" in e for e in errors))
        self.assertTrue(any("unexpected key 'extra'" in e for e in errors))

    def test_package_payload_required(self):
        errors = self.broken(lambda d: shutil.rmtree(d / "fixture-package" / "package"))
        self.assertTrue(any("non-empty package/ folder" in e for e in errors))

    def test_third_party_front_matter_required(self):
        def edit(d):
            self.edit_json(d / "fixture-skills" / "pack.json", lambda p: p.update(
                upstream="https://github.com/example/repo", upstream_commit="a" * 40,
                vetting={"status": "passed", "vetted": "2026-01-01"}))
        errors = self.broken(edit)
        self.assertTrue(any("origin: third-party" in e for e in errors))
        self.assertTrue(any("upstream must be the blob URL" in e for e in errors))

    def test_core_name_clash_fails(self):
        def edit(d):
            src = d / "fixture-skills" / "skills" / "fixture-three"
            md = src / "SKILL.md"
            md.write_text(md.read_text().replace("name: fixture-three", "name: grill-me"))
            src.rename(src.parent / "grill-me")
            self.edit_json(d / "fixture-skills" / "pack.json", lambda p: p["sets"][1].update(skills=["grill-me"]))
        self.assertTrue(any("name of a core skill" in e for e in self.broken(edit)))


