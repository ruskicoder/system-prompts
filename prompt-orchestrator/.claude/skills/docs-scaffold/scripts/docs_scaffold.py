    print(f"Initialized {args.type} scaffold at {proj.prel(proj.root)}/ "
          f"(changes: {changes}, ignore: {args.ignore_dir}/)")
    print(f"  created {len(created)} files")
    for rel in skipped:
        print(f"  kept existing file (not overwritten): {rel}")
    if note:
        print(f"  {note}")
    return 0


