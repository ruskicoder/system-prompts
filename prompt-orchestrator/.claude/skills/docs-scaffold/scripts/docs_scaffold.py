def ensure_ignored(proj):
    rel = proj.prel(proj.ignore)
    if not in_git(proj.project):
        return f"not a git repository: make sure {rel}/ is excluded from version control"
    if is_ignored(proj.project, f"{rel}/x"):
        return None
    gi = proj.project / ".gitignore"
    text = gi.read_text(encoding="utf-8") if gi.is_file() else ""
    sep = "" if not text or text.endswith("\n") else "\n"
    gi.write_text(text + sep + f"/{rel}/\n", encoding="utf-8")
    return f"added /{rel}/ to {proj.prel(gi)}"


def cmd_index_proj(proj, quiet=False):
    docs = live_docs(proj)
    for path, content in generated_files(proj, docs).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
    locks = read_locks(proj)
    added = []
    for rel, adr in lockables(proj, docs).items():
        if rel not in locks:
            locks[rel] = lock_hash(proj.root / rel, adr)
            added.append(rel)
    write_locks(proj, locks)
    if not quiet:
        print(f"Regenerated INDEX.md, _generated/traceability.md, .deprecated/README.md "
              f"({len(docs)} live documents); locked {len(added)} new files")
    return 0


