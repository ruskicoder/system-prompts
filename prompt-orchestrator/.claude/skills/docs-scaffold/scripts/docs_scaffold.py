class Doc:
    def __init__(self, path, rel, fm, body):
        self.path, self.rel, self.fm, self.body = path, rel, fm, body

    def get(self, key, default=""):
        return (self.fm or {}).get(key, default)


class Project:
    def __init__(self, project, manifest_path):
        self.project = project
        self.manifest_path = manifest_path
        try:
            self.m = json.loads(manifest_path.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise UsageError(f"invalid manifest {manifest_path}: {exc}")
        for key in ("type", "docs_root", "changes_dir", "ignore_dir"):
            if key not in self.m:
                raise UsageError(f"manifest {manifest_path} is missing '{key}'")
        self.root = (project / self.m["docs_root"]).resolve()
        self.changes = (project / self.m["changes_dir"]).resolve()
        self.ignore = (project / self.m["ignore_dir"]).resolve()
        self.locks_path = self.root / "90-meta" / "locks.json"

    def rel(self, path):
        return Path(os.path.relpath(str(path), str(self.root))).as_posix()

    def prel(self, path):
        return Path(os.path.relpath(str(path), str(self.project))).as_posix()

    @property
    def standalone(self):
        return self.m["type"] == "standalone"


def is_under(path, base):
    try:
        Path(path).resolve().relative_to(Path(base).resolve())
        return True
    except ValueError:
        return False


def find_project(args):
    project = Path(args.project).resolve()
    candidates = [project / args.root] if args.root else (
        [project / "docs", project] + sorted(p for p in project.iterdir() if p.is_dir()))
    for base in candidates:
        manifest = base / "90-meta" / "manifest.json"
        if manifest.is_file():
            return Project(project, manifest)
    raise UsageError("no docs scaffold found (90-meta/manifest.json); run `init` first")


def git(cwd, *args):
    try:
        return subprocess.run(("git",) + args, cwd=str(cwd), capture_output=True, text=True)
    except (FileNotFoundError, NotADirectoryError):
        return None


def git_out(cwd, *args):
    r = git(cwd, *args)
    return r.stdout.strip() if r is not None and r.returncode == 0 else None


def in_git(cwd):
    return git_out(cwd, "rev-parse", "--is-inside-work-tree") == "true"


def is_ignored(cwd, rel):
    r = git(cwd, "check-ignore", "-q", rel)
    return r is not None and r.returncode == 0


def load_doc(proj, path):
    text = path.read_text(encoding="utf-8", errors="replace")
    fm, body = split_doc(text)
    return Doc(path, proj.rel(path), fm, body)


def live_docs(proj):
    paths = [proj.root / n for n in TOP_FILES if n != "INDEX.md" and (proj.root / n).is_file()]
    for d in LIVE_DIRS:
        if (proj.root / d).is_dir():
            paths += sorted((proj.root / d).rglob("*.md"))
    return [load_doc(proj, p) for p in paths if not is_under(p, proj.changes)]


def repo_dirs(proj):
    """Map repo name -> local path (None when unavailable). '' is the project itself."""
    out = {"": proj.project}
    for name, spec in (proj.m.get("repos") or {}).items():
        env = (spec or {}).get("path_env", "")
        path = os.environ.get(env, "")
        out[name] = Path(path) if path and Path(path).is_dir() else None
    return out


def split_source(proj, source):
    name, sep, rest = source.partition(":")
    if proj.standalone and sep and name in (proj.m.get("repos") or {}):
        return name, rest
    return "", source


def group_sources(proj, sources):
    groups = {}
    for s in sources:
        repo, path = split_source(proj, s)
        groups.setdefault(repo, []).append(path)
    return groups


def changed_since(cwd, commit, paths):
    specs = [f":(glob){p}" for p in paths]
    diff = git_out(cwd, "diff", "--relative", "--name-only", commit, "--", *specs) or ""
    new = git_out(cwd, "ls-files", "--others", "--exclude-standard", "--", *specs) or ""
    return sorted(set(diff.splitlines() + new.splitlines()) - {""})


def section_state(proj, doc):
    """Return (state, detail): none | unverified | ok | stale | unverifiable | error."""
    sources = doc.get("sources", [])
    sources = [sources] if isinstance(sources, str) and sources else sources or []
    if not sources:
        return "none", ""
    verified = doc.get("verified", {})
    verified = verified if isinstance(verified, dict) else {}
    dirs = repo_dirs(proj)
    stale = []
    for repo, paths in group_sources(proj, sources).items():
        cwd = dirs.get(repo)
        label = repo or "project"
        if cwd is None or not in_git(cwd):
            return "unverifiable", f"repo '{label}' is not available as a local git clone"
        commit = verified.get(repo) or verified.get("commit") or ""
        if not commit:
            return "unverified", "no verified commit recorded"
        if git_out(cwd, "cat-file", "-e", f"{commit}^{{commit}}") is None:
            return "error", f"verified commit {commit} not found in repo '{label}'"
        stale += [f"{repo + ':' if repo else ''}{f}" for f in changed_since(cwd, commit, paths)]
    if stale:
        more = f" (+{len(stale) - 5} more)" if len(stale) > 5 else ""
        return "stale", ", ".join(stale[:5]) + more
    return "ok", ""


