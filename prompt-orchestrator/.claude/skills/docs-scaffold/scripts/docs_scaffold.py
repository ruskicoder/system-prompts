def esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_index(docs):
    rows = [f"| [{d.rel}]({d.rel}) | {esc(d.get('id', '?'))} | {esc(d.get('type', '?'))} | "
            f"{esc(d.get('status', '?'))} | {esc(d.get('summary', ''))} |"
            for d in sorted(docs, key=lambda d: d.rel)]
    return ("# Documentation Index\n\n" + GEN_MARK + "\n\n"
            "| Path | ID | Type | Status | Summary |\n|---|---|---|---|---|\n"
            + "\n".join(rows) + "\n")


def defined_ids(docs):
    ids = set()
    for d in docs:
        if d.get("type") in ("requirements", "nfr"):
            ids.update(ID_RE.findall(d.body))
    return ids


def trace_map(docs):
    out = {}
    for d in docs:
        traces = d.get("traces", [])
        for t in [traces] if isinstance(traces, str) else traces or []:
            out.setdefault(t, []).append(d)
    return out


def _natural(text):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", text)]


def render_traceability(docs):
    ids = sorted(defined_ids(docs), key=_natural)
    traces = trace_map(docs)
    lines = ["# Traceability", "", GEN_MARK, ""]
    if not ids:
        return "\n".join(lines + ["_No requirement IDs defined yet._", ""])
    lines += ["| Requirement | Design | Test | Other |", "|---|---|---|---|"]
    for rid in ids:
        ds = traces.get(rid, [])
        cell = lambda pred: ", ".join(sorted(d.get("id", d.rel) for d in ds if pred(d))) or "-"
        lines.append(f"| {rid} | {cell(lambda d: d.get('type') in DESIGN_TYPES)} | "
                     f"{cell(lambda d: d.get('type') in TEST_TYPES)} | "
                     f"{cell(lambda d: d.get('type') not in DESIGN_TYPES | TEST_TYPES)} |")
    return "\n".join(lines) + "\n"


def render_deprecated(proj):
    base = proj.root / ".deprecated"
    rows = []
    for d in sorted(p for p in base.iterdir() if p.is_dir()) if base.is_dir() else []:
        info = {}
        for f in sorted(d.rglob("*.md")):
            fm, _ = split_doc(f.read_text(encoding="utf-8", errors="replace"))
            if fm and isinstance(fm.get("deprecated"), dict):
                info = fm["deprecated"]
                break
        rows.append(f"| [{d.name}]({d.name}/) | {esc(info.get('date', '?'))} | "
                    f"`{esc(info.get('from', '?'))}` | {esc(info.get('reason', '?'))} | "
                    f"{esc(info.get('superseded_by', '?'))} |")
    body = "\n".join(rows) if rows else "| - | - | - | - | - |"
    return ("# Deprecated Documents\n\n" + GEN_MARK + "\n\n"
            "Preserved, read-only copies of wrong, mistaken, or substantively changed specs. "
            "Live documents must not link here.\n\n"
            "| Folder | Date | From | Reason | Superseded by |\n|---|---|---|---|---|\n"
            + body + "\n")


def generated_files(proj, docs):
    return {
        proj.root / "INDEX.md": render_index(docs),
        proj.root / "_generated" / "traceability.md": render_traceability(docs),
        proj.root / ".deprecated" / "README.md": render_deprecated(proj),
    }


def lock_hash(path, adr=False):
    data = path.read_bytes()
    if adr:
        data = b"\n".join(l for l in data.split(b"\n") if not l.lstrip().startswith(b"superseded_by:"))
    return hashlib.sha256(data).hexdigest()


def lockables(proj, docs):
    """Map rel path -> is_adr for every file that must never change again."""
    out = {}
    dep = proj.root / ".deprecated"
    if dep.is_dir():
        for f in dep.rglob("*"):
            if f.is_file() and f != dep / "README.md":
                out[proj.rel(f)] = False
    for d in docs:
        if d.rel.startswith("70-work/") and d.get("status") == "closed" and d.path.name != "STATUS.md":
            out[d.rel] = False
        if d.rel.startswith("60-decisions/") and d.get("type") == "adr" and d.get("status") == "approved":
            out[d.rel] = True
    return out


def read_locks(proj):
    if not proj.locks_path.is_file():
        return {}
    try:
        return json.loads(proj.locks_path.read_text(encoding="utf-8"))
    except ValueError:
        return {}


def write_locks(proj, locks):
    proj.locks_path.parent.mkdir(parents=True, exist_ok=True)
    proj.locks_path.write_text(json.dumps(dict(sorted(locks.items())), indent=2) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------
# Session journal (append-only, hash-chained across all session files)
# --------------------------------------------------------------------------

def sessions_dir(proj):
    return proj.ignore / "sessions"


def session_files(d):
    """Session files in creation order: YYYYMMDD-HHMMSS, then -2, -3 suffixes."""
    def key(p):
        m = re.match(r"^(\d{8}-\d{6})(?:-(\d+))?$", p.stem)
        return (m.group(1), int(m.group(2) or 1)) if m else (p.stem, 0)
    return sorted(d.glob("*.md"), key=key) if d.is_dir() else []


def journal(proj):
    entries = []
    for f in session_files(sessions_dir(proj)):
        for m in CHAIN_RE.finditer(f.read_text(encoding="utf-8")):
            entries.append({"file": f, "body": m.group(1), "prev": m.group(2), "hash": m.group(3)})
    return entries


def entry_hash(prev, body):
    return hashlib.sha256((prev + "\n" + body).encode("utf-8")).hexdigest()[:16]


def verify_chain(entries):
    problems, expected = [], GENESIS
    for e in entries:
        title = f"{e['file'].name} '{e['body'].splitlines()[0][4:]}'"
        if e["prev"] != expected:
            problems.append(f"{title} does not follow the previous entry (entry deleted or reordered)")
        if entry_hash(e["prev"], e["body"]) != e["hash"]:
            problems.append(f"{title} was modified after it was written")
        expected = e["hash"]
    return problems


def now():
    return dt.datetime.now().astimezone().replace(microsecond=0)


def git_facts(proj):
    lines = []
    for name, cwd in repo_dirs(proj).items():
        label = f"repo {name}" if name else "head"
        if cwd is None or not in_git(cwd):
            lines.append(f"{label}: unavailable")
            continue
        head = git_out(cwd, "rev-parse", "--short", "HEAD") or "none"
        branch = git_out(cwd, "rev-parse", "--abbrev-ref", "HEAD") or "?"
        status = git_out(cwd, "-c", "color.status=false", "status", "--short",
                         "--untracked-files=all", "--", ".") or ""
        changed = [" ".join(l.split()) for l in status.splitlines() if l.strip()]
        more = f" (+{len(changed) - 40} more)" if len(changed) > 40 else ""
        lines.append(f"{label}: {head} on {branch}")
        if not name:
            lines.append("changed: " + ("; ".join(changed[:40]) + more if changed else "clean"))
    return lines


def append_entry(proj, kind, result, lines, new_file=False):
    d = sessions_dir(proj)
    d.mkdir(parents=True, exist_ok=True)
    entries = journal(proj)
    prev = entries[-1]["hash"] if entries else GENESIS
    files = session_files(d)
    if new_file or not files:
        stamp = now().strftime("%Y%m%d-%H%M%S")
        target, n = d / f"{stamp}.md", 1
        while target.exists():
            n += 1
            target = d / f"{stamp}-{n}.md"
        target.write_text(f"# Session {target.stem}\n\n", encoding="utf-8")
    else:
        target = files[-1]
    number = sum(1 for e in entries if e["file"] == target) + 1
    clean = [" / ".join(str(l).splitlines()) for l in lines]
    body = f"### {number:03d} | {now().isoformat()} | {kind} | {result}\n" + "\n".join(f"- {l}" for l in clean)
    with target.open("a", encoding="utf-8") as fh:
        fh.write(f"{body}\n<!-- chain prev={prev} hash={entry_hash(prev, body)} -->\n\n")
    return target, number


def last_head(entries):
    for e in reversed(entries):
        m = re.search(r"^- head: ([0-9a-f]{4,40})\b", e["body"], re.M)
        if m:
            return m.group(1)
    return None


def resync_lines(proj, entries):
    lines = []
    prev_head = last_head(entries)
    head = git_out(proj.project, "rev-parse", "--short", "HEAD")
    if prev_head and head and prev_head != head:
        log = git_out(proj.project, "log", "--oneline", f"{prev_head}..HEAD", "--", ".")
        commits = (log or "").splitlines()
        lines.append("commits since last entry: " + ("; ".join(commits[:20]) if commits else
                     "none touching this project") + (f" (+{len(commits) - 20} more)" if len(commits) > 20 else ""))
    elif prev_head:
        lines.append("commits since last entry: none")
    stale = [d.rel for d in live_docs(proj) if d.get("type") == "section" and section_state(proj, d)[0] == "stale"]
    lines.append("stale sections: " + (", ".join(stale) if stale else "none"))
    return lines


