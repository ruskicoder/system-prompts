def run_checks(proj):
    findings = []

    def add(sev, check, path, msg, hint=""):
        findings.append((sev, check, path, msg, hint))

    docs = live_docs(proj)
    root_rel = proj.prel(proj.root)

    # structure
    for name in TOP_FILES:
        if not (proj.root / name).is_file():
            add("warn", "structure", name, "missing top-level file", "run `index` or `init`")
    for name in TOP_DIRS:
        if not (proj.root / name).is_dir():
            add("warn", "structure", name + "/", "missing top-level folder", "recreate it")
    prefixes = {}
    for p in proj.root.iterdir():
        m = re.match(r"^(\d+)-", p.name)
        if p.is_dir() and m:
            prefixes.setdefault(m.group(1), []).append(p.name)
    for prefix, names in prefixes.items():
        if len(names) > 1:
            add("warn", "structure", ", ".join(sorted(names)), f"duplicate numeric prefix {prefix}", "renumber one folder")
    for d in docs:
        if d.rel.count("/") > 3:
            add("warn", "structure", d.rel, "deeper than three folders below the docs root", "flatten")

    # tracking
    if in_git(proj.project):
        if is_ignored(proj.project, f"{root_rel}/README.md"):
            add("error", "tracking", root_rel, "docs root is git-ignored; docs must be tracked", "fix .gitignore")
        if is_ignored(proj.project, f"{proj.prel(proj.changes)}/x/requirements.md"):
            add("error", "tracking", proj.prel(proj.changes), "changes dir is git-ignored; specs must be tracked", "fix .gitignore")
        if not is_ignored(proj.project, f"{proj.prel(proj.ignore)}/x"):
            add("warn", "tracking", proj.prel(proj.ignore), "ignore dir is not git-ignored", "add it to .gitignore")

    # frontmatter
    seen = {}
    for d in docs:
        if d.fm is None:
            add("warn", "frontmatter", d.rel, "missing frontmatter", "add id, type, status, owner, summary")
            continue
        for key in REQUIRED_FM:
            if not str(d.get(key, "")).strip():
                add("warn", "frontmatter", d.rel, f"missing '{key}'", "fill it in")
        if d.get("type") and d.get("type") not in DOC_TYPES:
            add("warn", "frontmatter", d.rel, f"unknown type '{d.get('type')}'", "see 90-meta/conventions.md")
        if d.get("status") and d.get("status") not in STATUSES:
            add("warn", "frontmatter", d.rel, f"unknown status '{d.get('status')}'", "use " + ", ".join(STATUSES))
        if d.get("id"):
            seen.setdefault(d.get("id"), []).append(d.rel)
    for doc_id, rels in seen.items():
        if len(rels) > 1:
            add("error", "duplicate-id", ", ".join(rels), f"id '{doc_id}' used more than once", "make ids unique")

    # gaps
    for d in docs:
        status = d.get("status")
        if status == "todo":
            add("info", "gap", d.rel, "status todo", "write it or mark n/a with na_reason")
        elif status == "n/a" and not str(d.get("na_reason", "")).strip():
            add("warn", "gap", d.rel, "status n/a without na_reason", "add na_reason")
        elif d.fm is not None and is_empty(d.body) and status != "n/a":
            add("warn", "gap", d.rel, "document has no content", "write it or set status todo")
    kinds = proj.m.get("unit_kinds") or {"module": ["design.md", "tests.md"]}
    units_dir = proj.root / "30-units"
    units = []
    for p in sorted(units_dir.iterdir()) if units_dir.is_dir() else []:
        if not p.is_dir():
            continue
        readme = p / "README.md"
        is_group = not readme.is_file() and any(c.is_dir() for c in p.iterdir())
        units += sorted(c for c in p.iterdir() if c.is_dir()) if is_group else [p]
    for u in units:
        readme = u / "README.md"
        if not readme.is_file():
            add("warn", "gap", proj.rel(u) + "/", "unit has no README.md", f"run `new unit {u.name}`")
            continue
        kind = load_doc(proj, readme).get("kind", "module")
        if kind not in kinds:
            add("warn", "gap", proj.rel(readme), f"unknown unit kind '{kind}'", "declare it in manifest unit_kinds")
            continue
        for name in kinds[kind]:
            if not (u / name).is_file():
                add("warn", "gap", proj.rel(u / name), "required document missing", "create it (status todo is fine)")

    # coverage and traces
    ids = defined_ids(docs)
    traces = trace_map(docs)
    for rid in sorted(ids, key=_natural):
        types = {d.get("type") for d in traces.get(rid, [])}
        if not types & DESIGN_TYPES:
            add("warn", "coverage", rid, "not traced by any design document", "add it to a design doc's traces")
        if not types & TEST_TYPES:
            add("warn", "coverage", rid, "not traced by any test document", "add it to a test doc's traces")
    for t, ds in traces.items():
        if ID_RE.fullmatch(t) and t not in ids:
            add("warn", "trace", ", ".join(d.rel for d in ds), f"traces unknown id {t}", "define it or fix the trace")

    # links
    dep_root = proj.root / ".deprecated"
    for d in docs:
        for _, target in LINK_RE.findall(CODE_RE.sub("", COMMENT_RE.sub("", d.body))):
            if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#"):
                continue
            path = (d.path.parent / target.split("#")[0].replace("%20", " ")).resolve()
            if is_under(path, dep_root):
                add("error", "deprecated-link", d.rel, f"links into .deprecated/: {target}", "link the replacement instead")
            elif not path.exists():
                add("warn", "link", d.rel, f"broken link: {target}", "fix or remove it")

    # staleness and section size
    low, high = (proj.m.get("section_size") or [2, 10])[:2]
    for d in docs:
        if d.get("type") != "section":
            continue
        state, detail = section_state(proj, d)
        if state == "stale":
            add("warn", "stale", d.rel, "sources changed since verification: " + detail, "update the section, then `verify`")
        elif state == "unverified":
            add("warn", "stale", d.rel, "section has sources but was never verified", "review it, then `verify`")
        elif state == "unverifiable":
            add("warn", "stale", d.rel, "unverifiable: " + detail, "set the repo path env var")
        elif state == "error":
            add("error", "stale", d.rel, detail, "re-verify the section")
        count = sum(1 for f in d.path.parent.glob("*.md") if f.name != "README.md")
        if not low <= count <= high:
            add("warn", "section-size", d.rel, f"section holds {count} documents (expected {low}-{high})", "merge or split")

    # locks
    locks = read_locks(proj)
    lockable = lockables(proj, docs)
    for rel, digest in sorted(locks.items()):
        path = proj.root / rel
        if not path.is_file():
            add("error", "immutable", rel, "locked file was deleted or moved", "restore it from git")
        elif lock_hash(path, lockable.get(rel, rel.startswith("60-decisions/"))) != digest:
            add("error", "immutable", rel, "locked file was modified", "restore it; record changes in a new document")
    for rel in sorted(set(lockable) - set(locks)):
        add("warn", "immutable", rel, "closed record is not locked yet", "run `index`")

    # generated files
    for path, content in generated_files(proj, docs).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            add("warn", "generated", proj.rel(path), "generated file is out of date", "run `index`")

    # session journal (local only)
    entries = journal(proj)
    for problem in verify_chain(entries):
        add("error", "journal", proj.prel(sessions_dir(proj)), problem, "journals are append-only; restore the file")
    status = proj.root / "70-work" / "STATUS.md"
    if status.is_file():
        m = re.search(r"journal: \S+ entry \d+ hash ([0-9a-f]{16})", status.read_text(encoding="utf-8"))
        if m and entries and m.group(1) not in {e["hash"] for e in entries}:
            add("error", "journal", "70-work/STATUS.md", "entry recorded at last sync is missing from the journal (truncated or replaced)", "restore the journal")
        elif m and not entries:
            add("info", "journal", proj.prel(sessions_dir(proj)), "no local journal on this machine", "run `session start`")
    return findings, docs


def print_findings(findings):
    order = {"error": 0, "warn": 1, "info": 2}
    for sev, check, path, msg, hint in sorted(findings, key=lambda f: (order[f[0]], f[1], f[2])):
        print(f"[{sev.upper():5}] {check:15} {path}: {msg}" + (f"  -> {hint}" if hint else ""))
    counts = {s: sum(1 for f in findings if f[0] == s) for s in order}
    summary = f"{counts['error']} error, {counts['warn']} warn, {counts['info']} info"
    print(f"\n{summary} (warn-only: exit code 0)")
    return summary


def write_health(proj, findings, summary):
    lines = [f"# Docs health ({now().isoformat()})", "", summary, ""]
    lines += [f"- [{s}] {c} `{p}`: {m}" + (f" (fix: {h})" if h else "") for s, c, p, m, h in findings]
    proj.ignore.mkdir(parents=True, exist_ok=True)
    (proj.ignore / "health.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


