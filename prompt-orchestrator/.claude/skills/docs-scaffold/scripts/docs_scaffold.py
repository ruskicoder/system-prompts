def cmd_init(args):
    project = Path(args.project).resolve()
    root = args.root or "docs"
    manifest_path = project / root / "90-meta" / "manifest.json"
    if manifest_path.exists():
        raise UsageError(f"already initialized: {manifest_path}")
    changes = args.changes_dir or (".kiro/specs" if args.type == "embedded"
                                   else (Path(root) / "70-work" / "changes").as_posix())
    manifest = {"schema": SCHEMA, "type": args.type, "docs_root": root, "changes_dir": changes,
                "ignore_dir": args.ignore_dir, "repos": {}, "section_size": [2, 10],
                "unit_kinds": {"module": ["design.md", "tests.md"]}}
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    proj = Project(project, manifest_path)
    created, skipped = [], []
    for rel, content in scaffold_files(proj).items():
        write_new(proj.root / rel, content, created, skipped, proj.root)
    for d in ("_generated", ".deprecated"):
        (proj.root / d).mkdir(parents=True, exist_ok=True)
    if proj.standalone:
        proj.changes.mkdir(parents=True, exist_ok=True)
    write_locks(proj, read_locks(proj))
