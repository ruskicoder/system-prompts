#!/usr/bin/env python3
"""docs-scaffold: documentation SSOT scaffold, checks, deprecation, session journal.

Python 3.8+, standard library only. Every check is warn-only: `check` prints
findings and exits 0. Exit code 2 signals a usage or configuration error.

Commands (run from the project root, or pass --project):
  init --type embedded|standalone   create the scaffold and manifest
  check                             report gaps, stale sections, broken links, ...
  index                             regenerate INDEX.md, _generated/, .deprecated/README.md, locks
  new <kind> <name>                 unit | adr | investigation | review | release | test-run | change
  verify <section-dir>...           stamp sections as verified against the current commit
  deprecate <path> --reason ...     preserve a spec in .deprecated/ (--keep copies before an edit)
  session start|log|sync|resync|show   append-only session journal in the ignore dir
"""

