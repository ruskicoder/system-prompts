# --------------------------------------------------------------------------
# Frontmatter: flat `key: value` lines; values may be scalars, quoted strings,
# inline lists `[a, b]` or inline maps `{k: v}`. No nesting beyond one level.
# --------------------------------------------------------------------------

def _split_flow(text):
    parts, buf, quoted, escaped = [], "", False, False
    for ch in text:
        if quoted:
            buf += ch
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                quoted = False
        elif ch == '"':
            quoted, buf = True, buf + ch
        elif ch == ",":
            parts.append(buf)
            buf = ""
        else:
            buf += ch
    parts.append(buf)
    return [p.strip() for p in parts if p.strip()]


def _scalar(text):
    text = text.strip()
    if text.startswith('"'):
        try:
            return json.loads(text)
        except ValueError:
            return text.strip('"')
    if len(text) >= 2 and text[0] == text[-1] == "'":
        return text[1:-1]
    return text


def parse_value(text):
    text = text.strip()
    if text.startswith("[") and text.endswith("]"):
        return [_scalar(p) for p in _split_flow(text[1:-1])]
    if text.startswith("{") and text.endswith("}"):
        out = {}
        for part in _split_flow(text[1:-1]):
            key, _, val = part.partition(":")
            out[key.strip()] = _scalar(val)
        return out
    return _scalar(text)


def dump_value(value):
    if isinstance(value, list):
        return "[" + ", ".join(dump_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k}: {dump_value(v)}" for k, v in value.items()) + "}"
    text = str(value)
    return text if re.fullmatch(r"[A-Za-z0-9_./@*+-]+", text) else json.dumps(text)


def split_doc(text):
    """Return (frontmatter dict or None, body)."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            fm = {}
            for line in lines[1:i]:
                if line.strip() and not line.lstrip().startswith("#"):
                    key, sep, val = line.partition(":")
                    if sep:
                        fm[key.strip()] = parse_value(val)
            return fm, "\n".join(lines[i + 1:])
    return None, text


def set_frontmatter(text, key, value):
    line = f"{key}: {dump_value(value)}"
    lines = text.split("\n")
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                for j in range(1, i):
                    if lines[j].partition(":")[0].strip() == key:
                        lines[j] = line
                        return "\n".join(lines)
                lines.insert(i, line)
                return "\n".join(lines)
    return f"---\n{line}\n---\n\n{text}"


def render_doc(doc_id, doc_type, status, summary, body, **extra):
    fields = {"id": doc_id, "type": doc_type, "status": status, "owner": "unassigned",
              "summary": summary}
    fields.update(extra)
    head = "\n".join(f"{k}: {dump_value(v)}" for k, v in fields.items())
    return f"---\n{head}\n---\n\n{body.strip()}\n"


def default_id(rel):
    parts = [re.sub(r"^\d+-", "", p) for p in rel[:-3].split("/")]
    if parts[-1] == "README":
        parts = parts[:-1] or ["readme"]
    return ".".join(parts)


def is_empty(body):
    text = COMMENT_RE.sub("", body)
    return not any(l.strip() and not l.lstrip().startswith("#") for l in text.splitlines())


