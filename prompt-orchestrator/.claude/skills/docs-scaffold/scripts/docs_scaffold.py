def cmd_verify(args):
    proj = find_project(args)
    today = dt.date.today().isoformat()
    for target in args.sections:
        path = Path(target)
        readme = (path if path.name == "README.md" else path / "README.md").resolve()
        if not readme.is_file():
            raise UsageError(f"no section README.md at {target}")
        doc = load_doc(proj, readme)
        if doc.get("type") != "section":
            raise UsageError(f"{target} is not a section (README type must be 'section')")
        sources = doc.get("sources", [])
        sources = [sources] if isinstance(sources, str) and sources else sources or []
        if not sources:
            raise UsageError(f"{target} has no sources; add code globs before verifying")
        verified = {}
        for repo, paths in group_sources(proj, sources).items():
            cwd = repo_dirs(proj).get(repo)
            if cwd is None or not in_git(cwd):
                raise UsageError(f"repo '{repo or 'project'}' is not available as a local git clone")
            dirty = git_out(cwd, "status", "--porcelain", "--", *[f":(glob){p}" for p in paths])
            if dirty:
                print(f"warning: {target}: uncommitted changes in sources are not covered by this stamp")
            verified[repo or "commit"] = git_out(cwd, "rev-parse", "--short", "HEAD")
        verified["date"] = today
        text = readme.read_text(encoding="utf-8")
        readme.write_text(set_frontmatter(text, "verified", verified), encoding="utf-8")
        print(f"verified {proj.rel(readme)}: {dump_value(verified)}")
    return 0


def cmd_deprecate(args):
    proj = find_project(args)
    src = Path(args.path).resolve()
    if not src.exists():
        raise UsageError(f"not found: {args.path}")
    dep_root = proj.root / ".deprecated"
    if is_under(src, dep_root):
        raise UsageError("already deprecated")
    if not (is_under(src, proj.root) or is_under(src, proj.changes)):
        raise UsageError("only documents under the docs root or the changes dir can be deprecated")
    docs = live_docs(proj)
    by_id = {d.get("id"): d for d in docs if d.get("id")}
    superseded = args.superseded_by
    if superseded is None:
        own = load_doc(proj, src).get("id") if src.is_file() else ""
        if args.keep and own:
            superseded = own
        else:
            raise UsageError("--superseded-by is required (an id, or 'none')")
    if superseded != "none" and superseded not in by_id and not args.keep:
        raise UsageError(f"--superseded-by '{superseded}' is not a live document id")
    today = dt.date.today().isoformat()
    slug = re.sub(r"[^a-z0-9]+", "-", (src.stem if src.is_file() else src.name).lower()).strip("-")
    dest, n = dep_root / f"{today}-{slug}", 1
    while dest.exists():
        n += 1
        dest = dep_root / f"{today}-{slug}-{n}"
    dest.mkdir(parents=True)
    origin = proj.prel(src)
    if src.is_file():
        (shutil.copy2 if args.keep else shutil.move)(str(src), str(dest / src.name))
    elif args.keep:
        shutil.copytree(str(src), str(dest), dirs_exist_ok=True)
    else:
        for child in list(src.iterdir()):
            shutil.move(str(child), str(dest / child.name))
        src.rmdir()
    stamp = {"date": today, "from": origin, "reason": args.reason, "superseded_by": superseded}
    for md in sorted(dest.rglob("*.md")):
        md.write_text(set_frontmatter(md.read_text(encoding="utf-8"), "deprecated", stamp), encoding="utf-8")
    locks = read_locks(proj)
    for f in dest.rglob("*"):
        if f.is_file():
            locks[proj.rel(f)] = lock_hash(f)
    write_locks(proj, locks)
    rewritten, removed = (0, []) if args.keep else relink(proj, src, by_id.get(superseded))
    cmd_index_proj(proj, quiet=True)
    print(f"deprecated {origin} -> {proj.prel(dest)} ({'copied, original kept for editing' if args.keep else 'moved'})")
    if rewritten:
        print(f"  relinked {rewritten} links to {superseded}")
    for item in removed:
        print(f"  removed link (no replacement): {item}")
    return 0


def relink(proj, old, replacement):
    """Point live links at `old` to the replacement doc, or drop them."""
    count, removed = 0, []
    paths = [d.path for d in live_docs(proj)]
    if proj.changes.is_dir():
        paths += sorted(proj.changes.rglob("*.md"))
    for path in paths:
        text = path.read_text(encoding="utf-8")

        def fix(m):
            nonlocal count
            target = m.group(2)
            if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#"):
                return m.group(0)
            resolved = (path.parent / target.split("#")[0]).resolve()
            if resolved != old and not is_under(resolved, old):
                return m.group(0)
            if replacement is not None and replacement.path.exists():
                count += 1
                new = Path(os.path.relpath(str(replacement.path), str(path.parent))).as_posix()
                return f"[{m.group(1)}]({new})"
            removed.append(f"{proj.prel(path)}: {target}")
            return m.group(1)

        new_text = LINK_RE.sub(fix, text)
        if new_text != text:
            path.write_text(new_text, encoding="utf-8")
    return count, removed


def update_status(proj, lines):
    path = proj.root / "70-work" / "STATUS.md"
    text = path.read_text(encoding="utf-8") if path.is_file() else scaffold_files(proj)["70-work/STATUS.md"]
    block = f"{SYNC_START}\n" + "\n".join(f"- {l}" for l in lines) + f"\n{SYNC_END}"
    if SYNC_START in text and SYNC_END in text:
        text = re.sub(re.escape(SYNC_START) + r".*?" + re.escape(SYNC_END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + f"\n\n## Last sync\n\n{block}\n"
    path.write_text(text, encoding="utf-8")


def cmd_session(args):
    proj = find_project(args)
    entries = journal(proj)
    problems = verify_chain(entries)
    for p in problems:
        print(f"[ERROR] journal: {p}")
    if args.action == "show":
        for e in entries[-args.n:]:
            print(f"[{e['file'].name}]\n{e['body']}\n")
        print(f"{len(entries)} entries; chain {'BROKEN' if problems else 'intact'}")
        return 0
    if args.action == "start":
        ensure_ignore_scaffold(proj)
        if entries:
            print("Previous entries:")
            for e in entries[-args.n:]:
                print(f"[{e['file'].name}]\n{e['body']}\n")
        lines = git_facts(proj)
        if args.goal:
            lines.append(f"goal: {args.goal}")
        if entries:
            lines.append(f"previous: {entries[-1]['file'].name} hash {entries[-1]['hash']}")
        lines += resync_lines(proj, entries)
        target, number = append_entry(proj, "start", "info", lines, new_file=True)
    elif args.action == "log":
        if not entries:
            raise UsageError("no session journal yet; run `session start` first")
        if not args.what:
            raise UsageError("session log requires --action")
        lines = git_facts(proj) + [f"action: {args.what}"]
        if args.note:
            lines.append(f"note: {args.note}")
        target, number = append_entry(proj, "log", args.result, lines)
    elif args.action == "resync":
        if not entries:
            raise UsageError("no session journal yet; run `session start` first")
        target, number = append_entry(proj, "resync", "info", git_facts(proj) + resync_lines(proj, entries))
    else:  # sync
        if not entries:
            raise UsageError("no session journal yet; run `session start` first")
        findings, _ = run_checks(proj)
        counts = {s: sum(1 for f in findings if f[0] == s) for s in ("error", "warn", "info")}
        health = f"{counts['error']} error, {counts['warn']} warn, {counts['info']} info"
        target, number = append_entry(proj, "sync", "info", git_facts(proj) + [f"health: {health}"]
                                      + ([f"note: {args.note}"] if args.note else []))
        last = journal(proj)[-1]
        head = git_out(proj.project, "rev-parse", "--short", "HEAD") or "none"
        update_status(proj, [f"last_sync: {now().isoformat()}", f"head: {head}",
                             f"journal: {last['file'].name} entry {number:03d} hash {last['hash']}",
                             f"health: {health}"])
    print(f"appended entry {number:03d} to {proj.prel(target)}")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", default=".", help="project root (default: current directory)")
    parser.add_argument("--root", default=None, help="docs root relative to the project (default: discovered)")
    # Accept the global options after the subcommand too (`init --type x --root .`).
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--project", default=argparse.SUPPRESS, help=argparse.SUPPRESS)
    common.add_argument("--root", default=argparse.SUPPRESS, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="cmd", required=True)
    _add = sub.add_parser
    sub.add_parser = lambda *a, **k: _add(*a, parents=[common], **k)

    p = sub.add_parser("init", help="create the scaffold")
    p.add_argument("--type", required=True, choices=SCAFFOLD_TYPES)
    p.add_argument("--changes-dir", default=None)
    p.add_argument("--ignore-dir", default="ignore")
    p.set_defaults(func=cmd_init)

    sub.add_parser("check", help="warn-only health check").set_defaults(func=cmd_check)
    sub.add_parser("index", help="regenerate generated files and locks").set_defaults(
        func=lambda a: cmd_index_proj(find_project(a)))

    p = sub.add_parser("new", help="create a unit, decision, work record, or change")
    p.add_argument("kind", choices=("unit", "adr", "change") + tuple(WORK_KINDS))
    p.add_argument("name")
    p.add_argument("--unit-kind", default="module")
    p.add_argument("--group", default=None, help="optional grouping folder for units")
    p.set_defaults(func=cmd_new)

    p = sub.add_parser("verify", help="stamp sections as verified at the current commit")
    p.add_argument("sections", nargs="+")
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("deprecate", help="preserve a spec in .deprecated/")
    p.add_argument("path")
    p.add_argument("--reason", required=True)
    p.add_argument("--superseded-by", default=None)
    p.add_argument("--keep", action="store_true", help="copy instead of move (before a substantive edit)")
    p.set_defaults(func=cmd_deprecate)

    p = sub.add_parser("session", help="append-only session journal")
    p.add_argument("action", choices=("start", "log", "sync", "resync", "show"))
    p.add_argument("--action", dest="what", default=None, help="what was done (session log)")
    p.add_argument("--result", default="ok", choices=("ok", "fail", "partial", "info"))
    p.add_argument("--note", default=None)
    p.add_argument("--goal", default=None)
    p.add_argument("-n", type=int, default=5, help="entries to print")
    p.set_defaults(func=cmd_session)

    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except UsageError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
