#!/usr/bin/env python3
"""Generate the native installers from install/spec.json and packs/*/pack.json.

    python3 tools/generate_installers.py            write install/install.sh, install.ps1, install.cmd
    python3 tools/generate_installers.py --check    exit 1 when a committed installer is stale

Options for tests and fixtures:
    --packs-dir DIR     read packs from DIR (default: packs/ from the spec)
    --out DIR           write the three installers into DIR (default: install/)
    --source-root DIR   embed DIR as the source folder (default: the installer's parent folder)

The emitted installers need no Python for the core and the packs: install.sh runs on bash 3.2
or later (Linux, macOS), install.ps1 on Windows PowerShell 5.1 or PowerShell 7, and install.cmd
starts install.ps1 from cmd or a double-click. The harness part calls
harness/scripts/install_harness.py and keeps its Python 3.11 requirement.

The runtime logic lives in tools/installer/runtime.sh and runtime.ps1. This script prepends a
header and a data block built from the spec and the packs. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "install" / "spec.json"
TEMPLATES = Path(__file__).resolve().parent / "installer"
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_packs  # noqa: E402

HEADER = ("Generated by tools/generate_installers.py from install/spec.json and packs/*/pack.json.",
          "Do not edit this file: edit the spec or a pack.json, then run python3 tools/generate_installers.py")


# ------------------------------------------------------------------ model

def load_model(packs_dir: Path, source_root: Path | None) -> dict:
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    packs, errors = validate_packs.load_packs(packs_dir)
    if errors:
        raise SystemExit("pack validation failed:\n  " + "\n  ".join(errors))
    base = source_root or ROOT
    packs_rel = os.path.relpath(packs_dir.resolve(), base.resolve()).replace(os.sep, "/")
    model_packs = []
    for pack in packs:
        entry = {key: pack[key] for key in ("id", "label", "description", "kind", "license", "upstream")}
        entry["payload"] = (pack.get("package") or {}).get("payload", "")
        entry["sets"] = [dict(s, count=len(s["skills"])) for s in pack["sets"]]
        entry["release"] = pack.get("release")
        if entry["release"]:
            entry["release"] = dict(entry["release"], bundle_env=pack["id"].upper().replace("-", "_") + "_BUNDLE_PATH")
        model_packs.append(entry)
    return {
        "spec": spec,
        "packs": model_packs,
        "packs_rel": packs_rel,
        "source_root": str(source_root.resolve()) if source_root else None,
    }


# ------------------------------------------------------------------ bash

def sq(value) -> str:
    """Single-quote a string for bash."""
    return "'" + str(value).replace("'", "'\\''") + "'"


def bash_case(func: str, key_expr: str, cases: list[tuple[str, str]], heredoc: bool = False) -> str:
    lines = [f"{func}() {{", f"    case \"{key_expr}\" in"]
    for key, value in cases:
        if heredoc:
            lines.append(f"        {sq(key)}) cat <<'PO_EOF'\n{value}\nPO_EOF\n            ;;")
        else:
            lines.append(f"        {sq(key)}) printf '%s' {sq(value)} ;;")
    lines += ["        *) printf '' ;;", "    esac", "}"]
    return "\n".join(lines)


def bash_location(name: str, alts: list[dict]) -> list[str]:
    var = f"L_{name}"
    out = []
    for i, alt in enumerate(alts):
        if "env" in alt:
            cond = f'[ -n "${{{alt["env"]}:-}}" ]'
            value = f'"${{{alt["env"]}}}' + (f'/{alt["join"]}"' if alt.get("join") else '"')
        else:
            cond = f'[ -d "$(po_expand {sq(alt["if_dir"])})" ]' if alt.get("if_dir") else "true"
            value = f'"$(po_expand {sq(alt["path"])})"'
        keyword = "if" if i == 0 else "elif"
        out.append(f"    {keyword} {cond}; then {var}={value}")
    out.append(f'    else po_die "cannot resolve the {name} location"; fi')
    return out


def step_line(step: dict) -> str:
    op = step["op"]
    if op in ("tree", "file", "doc"):
        fields = [step["src"], step["dest"]]
    elif op == "block":
        fields = [step["dest"], step["marker"], step["text"]]
    elif op == "attribution":
        fields = [step["script"], step["hooks_path"], "|".join(step["track"])]
    elif op == "plugin":
        fields = [step["src"], step["mirror"], step["dest"], step["backups"]]
    else:
        raise SystemExit(f"unknown step op {op}")
    for field in fields:
        if "\t" in field or "\n" in field:
            raise SystemExit(f"step field holds a tab or newline: {field!r}")
    return "\t".join([op, *fields])


def render_bash(model: dict) -> str:
    spec = model["spec"]
    tools = spec["tools"]
    harness = spec["harness"]
    packs = model["packs"]
    out = ["#!/usr/bin/env bash", *(f"# {line}" for line in HEADER), "#",
           "# prompt-orchestrator installer for Linux and macOS. Run: bash install/install.sh --help",
           "set -euo pipefail", ""]
    if model["source_root"]:
        out.append(f"PO_ROOT={sq(model['source_root'])}")
    else:
        out.append('PO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"')
    out += [
        f"PO_PACKS_REL={sq(model['packs_rel'])}",
        f"PO_MANIFEST_NAME={sq(spec['manifest'])}",
        f"PO_TOOLS={sq(' '.join(t['id'] for t in tools))}",
        f"PO_DEFAULT_TOOLS={sq(' '.join(t['id'] for t in tools if t['default']))}",
        f"PO_HARNESS_TOOLS={sq(' '.join(t['id'] for t in tools if t.get('harness')))}",
        f"PO_HARNESS_SCRIPT={sq(harness['script'])}",
        f"PO_HARNESS_PY_MAJOR={harness['python'][0]}",
        f"PO_HARNESS_PY_MINOR={harness['python'][1]}",
        f"PO_HARNESS_DEFAULT={1 if harness['default'] else 0}",
        f"PO_HARNESS_OPTIONS={sq(' '.join(o['id'] for o in harness['options']))}",
        f"PO_PACKS={sq(' '.join(p['id'] for p in packs))}",
        "",
        "# shellcheck disable=SC2034  # the L_* locations are read through po_expand",
        "po_init_locations() {",
    ]
    for name, forms in spec["locations"].items():
        out += bash_location(name, forms["posix"])
    out += ["}", ""]
    out.append(bash_case("po_tool_label", "$1", [(t["id"], t["label"]) for t in tools]))
    out.append(bash_case("po_tool_steps", "$1", [(t["id"], "\n".join(step_line(s) for s in t["steps"]))
                                                 for t in tools if t["steps"]], heredoc=True))
    out.append(bash_case("po_tool_skills", "$1", [(t["id"], "\n".join(t["skills"])) for t in tools if t["skills"]],
                         heredoc=True))
    out.append(bash_case("po_project_label", "$1", [(p["id"], p["label"]) for p in spec["projects"]]))
    out.append(bash_case("po_project_steps", "$1", [(p["id"], "\n".join(step_line(s) for s in p["steps"]))
                                                    for p in spec["projects"]], heredoc=True))
    out.append(bash_case("po_harness_family", "$1", list(harness["profile_tools"].items())))
    out.append(bash_case("po_harness_profiles", "$1", [(k, " ".join(v)) for k, v in harness["profiles"].items()]))
    out.append(bash_case("po_harness_option_label", "$1", [(o["id"], o["label"]) for o in harness["options"]]))
    pack_fields, set_fields, release_fields, providers = [], [], [], []
    for pack in packs:
        pid = pack["id"]
        for key in ("label", "description", "kind", "license", "payload"):
            pack_fields.append((f"{pid}:{key}", pack[key] or ""))
        pack_fields.append((f"{pid}:sets", " ".join(s["id"] for s in pack["sets"])))
        for entry in pack["sets"]:
            for key in ("label", "description"):
                set_fields.append((f"{pid}:{entry['id']}:{key}", entry[key]))
            set_fields.append((f"{pid}:{entry['id']}:count", str(entry["count"])))
            set_fields.append((f"{pid}:{entry['id']}:skills", " ".join(entry["skills"])))
        release = pack["release"]
        if release:
            for key in ("lock", "tag", "bundle", "engine", "bundle_env"):
                release_fields.append((f"{pid}:{key}", release[key]))
            release_fields.append((f"{pid}:roots", "\n".join(release["skill_roots"])))
            release_fields.append((f"{pid}:hook_files", "\n".join(release["hook_files"])))
            release_fields.append((f"{pid}:codex_hooks", "\n".join(
                "\t".join([h["event"], h["matcher"] or "-", str(h["timeout"]), h["status"]])
                for h in release["codex_hooks"])))
            providers += [(f"{pid}:{tool}", prov) for tool, prov in release["providers"].items()]
    out.append(bash_case("po_pack_get", "$1:$2", pack_fields))
    out.append(bash_case("po_set_get", "$1:$2:$3", set_fields))
    out.append(bash_case("po_release_get", "$1:$2", release_fields))
    out.append(bash_case("po_release_provider", "$1:$2", providers))
    out.append("")
    out.append((TEMPLATES / "runtime.sh").read_text(encoding="utf-8").rstrip("\n"))
    out += ["", 'po_main "$@"', ""]
    return "\n".join(out)


# ------------------------------------------------------------------ PowerShell

def ps_lit(value, indent: int = 0) -> str:
    pad = "    " * (indent + 1)
    if value is None:
        return "$null"
    if isinstance(value, bool):
        return "$true" if value else "$false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    if isinstance(value, (list, tuple)):
        if not value:
            return "@()"
        items = [ps_lit(v, indent + 1) for v in value]
        return "@(\n" + ",\n".join(pad + i for i in items) + "\n" + "    " * indent + ")"
    if isinstance(value, dict):
        if not value:
            return "[ordered]@{}"
        items = [f"{pad}{ps_lit(str(k))} = {ps_lit(v, indent + 1)}" for k, v in value.items()]
        return "[ordered]@{\n" + "\n".join(items) + "\n" + "    " * indent + "}"
    raise TypeError(type(value))


def render_powershell(model: dict) -> str:
    spec = model["spec"]
    data = {
        "packs_rel": model["packs_rel"],
        "manifest": spec["manifest"],
        "locations": {name: forms["windows"] for name, forms in spec["locations"].items()},
        "tools": spec["tools"],
        "projects": spec["projects"],
        "harness": spec["harness"],
        "packs": model["packs"],
    }
    out = [*(f"# {line}" for line in HEADER), "#",
           "# prompt-orchestrator installer for Windows. Run: powershell -ExecutionPolicy Bypass -File install\\install.ps1 --help",
           "# Arguments use the same names as install.sh, for example --tools claude,codex --yes.",
           "$ErrorActionPreference = 'Stop'", ""]
    if model["source_root"]:
        out.append(f"$PO_Root = {ps_lit(model['source_root'])}")
    else:
        out.append("$PO_Root = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))")
    out.append(f"$PO_Data = {ps_lit(data)}")
    out.append("")
    out.append((TEMPLATES / "runtime.ps1").read_text(encoding="utf-8").rstrip("\n"))
    out += ["", "exit (Invoke-PoMain $args)", ""]
    return "\r\n".join("\n".join(out).split("\n"))


def render_cmd(model: dict) -> str:
    lines = [
        "@echo off",
        *(f"rem {line}" for line in HEADER),
        "rem prompt-orchestrator launcher for cmd and a double-click: it runs install.ps1 with the same arguments.",
        "setlocal",
        'set "PO_PS=powershell"',
        'where pwsh >nul 2>nul && set "PO_PS=pwsh"',
        '"%PO_PS%" -NoProfile -ExecutionPolicy Bypass -File "%~dp0install.ps1" %*',
        'set "PO_RC=%ERRORLEVEL%"',
        'echo %CMDCMDLINE% | findstr /i /c:"/c" >nul && pause',
        "exit /b %PO_RC%",
        "",
    ]
    return "\r\n".join(lines)


# ------------------------------------------------------------------ main

def outputs(model: dict, out_dir: Path) -> dict[Path, str]:
    return {
        out_dir / "install.sh": render_bash(model),
        out_dir / "install.ps1": render_powershell(model),
        out_dir / "install.cmd": render_cmd(model),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report stale installers and change nothing")
    parser.add_argument("--packs-dir", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--source-root", type=Path, default=None)
    args = parser.parse_args(argv)
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    packs_dir = (args.packs_dir or ROOT / spec["packs_dir"]).resolve()
    out_dir = (args.out or ROOT / "install").resolve()
    model = load_model(packs_dir, args.source_root)
    stale = []
    for path, text in outputs(model, out_dir).items():
        data = text.encode("utf-8")
        current = path.read_bytes() if path.exists() else None
        if current == data:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            if path.suffix == ".sh":
                path.chmod(0o755)
    shown = [str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p) for p in stale]
    if args.check:
        if stale:
            print("stale installers: " + ", ".join(shown))
            print("run: python3 tools/generate_installers.py")
            return 1
        print("installers are current")
        return 0
    print(("wrote " + ", ".join(shown)) if stale else "installers are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
