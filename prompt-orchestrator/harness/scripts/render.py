#!/usr/bin/env python3
"""Render canonical harness agents into each tool's native agent format (standard library only).

Used by tools/generate_integrations.py to build harness/dist/, and by the installer and
/autosetup to re-render Claude and Codex agents for the active profile on the user's machine.
Fields per tool follow the tools' docs as checked on 2026-10-30; a field that could not be
confirmed is left out rather than guessed.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

if __package__ in (None, ""):
    import harness_lib as h
else:  # pragma: no cover
    from . import harness_lib as h

AGENTS_DIR = h.HARNESS_HOME / "agents"
TIERS = ("frontier", "lead", "worker", "light", "inherit")
EFFORTS = ("medium", "high", "xhigh")
READ_ONLY_TOOLS = "Write, Edit, NotebookEdit"
TOOL_PROFILES = {
    "claude": ("claude-max", "claude-pro", "api", "free"),
    "codex": ("codex-plus", "api", "free"),
    "opencode": ("claude-max", "claude-pro", "api", "free"),
    "cursor": ("generic",), "copilot": ("generic",), "gemini": ("generic",),
    "antigravity": ("generic",), "kiro": ("generic",),
}
HEADER = f"generated by {h.MARKER} from harness/agents/{{name}}.md; edit the source, not this file"
FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.S)


# ---------------------------------------------------------------- canonical source

def _scalar(raw: str):
    value = raw.strip()
    if value.startswith("[") and value.endswith("]"):
        return [v.strip().strip("'\"") for v in value[1:-1].split(",") if v.strip()]
    if value in ("true", "false"):
        return value == "true"
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


def parse_agent(path: Path) -> dict:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise ValueError(f"{path}: missing frontmatter")
    meta = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"{path}: bad frontmatter line {line!r}")
        meta[key.strip()] = _scalar(value.split(" #")[0] if not value.strip().startswith(("'", '"')) else value)
    meta["body"] = text[match.end():].strip() + "\n"
    meta["source"] = path
    return meta


def load_agents(folder: Path = AGENTS_DIR) -> list[dict]:
    return [parse_agent(p) for p in sorted(folder.glob("*.md"))]


def validate_agent(agent: dict) -> list[str]:
    errors = []
    for field in ("name", "description", "tier", "effort", "access"):
        if not agent.get(field):
            errors.append(f"missing {field}")
    if agent.get("name") and agent["source"].stem != agent["name"]:
        errors.append("file name must match name")
    if agent.get("tier") not in TIERS:
        errors.append(f"tier must be one of {TIERS}")
    if agent.get("effort") not in EFFORTS:
        errors.append(f"effort must be one of {EFFORTS} (never low)")
    if agent.get("access") not in ("read", "write"):
        errors.append("access must be read or write")
    if agent.get("isolation") not in (None, "none", "worktree"):
        errors.append("isolation must be none or worktree")
    if len(str(agent.get("description", ""))) > 300:
        errors.append("description over 300 characters")
    return errors


def description_overlap(agents: list[dict], threshold: float = 0.6) -> list[str]:
    """Pairs of agents whose descriptions share too many content words (bad for delegation)."""
    stop = {"the", "a", "an", "and", "or", "of", "to", "for", "in", "on", "with", "it", "its", "is", "only",
            "use", "when", "returns", "return", "read-only", "by", "from", "one", "no", "not", "as", "that"}
    words = {a["name"]: {w for w in re.findall(r"[a-z]+", a["description"].lower()) if w not in stop}
             for a in agents}
    problems = []
    names = sorted(words)
    for i, left in enumerate(names):
        for right in names[i + 1:]:
            union = words[left] | words[right]
            if union and len(words[left] & words[right]) / len(union) >= threshold:
                problems.append(f"{left} and {right} descriptions overlap")
    return problems


# ---------------------------------------------------------------- helpers

def q(value) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def tier_model(agent: dict, profile: dict, table: str = "tiers") -> str:
    tier = agent["tier"]
    if tier == "inherit" or not profile:
        return ""
    return str(profile.get(table, {}).get(tier) or "")


def body_for(agent: dict, explicit_read_only: bool) -> str:
    body = agent["body"]
    if explicit_read_only and agent["access"] == "read":
        body = ("You are read-only: do not create, edit or delete files, and run only commands that do not "
                "change the repository.\n\n" + body)
    return body


def frontmatter(fields: list[tuple[str, object]], name: str) -> str:
    lines = ["---", f"# {HEADER.format(name=name)}"]
    for key, value in fields:
        if value in (None, "", []):
            continue
        if isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, list):
            lines.append(f"{key}: [{', '.join(q(v) for v in value)}]")
        elif isinstance(value, dict):
            lines.append(f"{key}:")
            lines += [f"  {k}: {v}" for k, v in value.items()]
        else:
            lines.append(f"{key}: {q(value) if isinstance(value, str) else value}")
    return "\n".join(lines + ["---", ""])


# ---------------------------------------------------------------- renderers

def render_claude(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("name", agent["name"]), ("description", agent["description"]),
              ("model", tier_model(agent, profile)), ("effort", agent["effort"])]
    if agent["access"] == "read":
        fields.append(("disallowedTools", READ_ONLY_TOOLS))
    if agent.get("omit_claude_md"):
        fields.append(("omitClaudeMd", True))
    fields.append(("skills", agent.get("skills") or []))
    if agent.get("isolation") == "worktree":
        fields.append(("isolation", "worktree"))
    return f"agents/{agent['name']}.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, False)


def clamp_effort(effort: str, supported: list[str] | None) -> str:
    if not supported or effort in supported:
        return effort
    order = ["low", "medium", "high", "xhigh", "max", "ultra"]
    above = [e for e in order[order.index(effort):] if e in supported]
    return above[0] if above else supported[-1]


def render_codex(agent: dict, profile: dict) -> tuple[str, str]:
    model = tier_model(agent, profile)
    supported = (profile.get("efforts") or {}).get(model) if profile else None
    body = body_for(agent, True).replace('"""', '\\"\\"\\"')
    lines = [f"# {HEADER.format(name=agent['name'])}", f"name = {q(agent['name'])}",
             f"description = {q(agent['description'])}"]
    if model:
        lines.append(f"model = {q(model)}")
    lines.append(f"model_reasoning_effort = {q(clamp_effort(agent['effort'], supported))}")
    lines.append(f'developer_instructions = """\n{body}"""')
    return f"agents/{agent['name']}.toml", "\n".join(lines) + "\n"


def render_opencode(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("description", agent["description"]), ("mode", "subagent"),
              ("model", tier_model(agent, profile, "opencode"))]
    if agent["access"] == "read":
        fields.append(("permission", {"edit": "deny"}))
    return f"agents/{agent['name']}.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, True)


def render_cursor(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("name", agent["name"]), ("description", agent["description"]), ("model", "inherit"),
              ("readonly", agent["access"] == "read")]
    return f"agents/{agent['name']}.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, True)


def render_copilot(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("name", agent["name"]), ("description", agent["description"])]
    return f"agents/{agent['name']}.agent.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, True)


def render_gemini(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("name", agent["name"]), ("description", agent["description"]), ("model", "inherit")]
    return f"agents/{agent['name']}.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, True)


def render_antigravity(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("name", agent["name"]), ("description", agent["description"]), ("model", "inherit"),
              ("subagent", True), ("mainAgent", False)]
    return f"agents/{agent['name']}.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, True)


def render_kiro(agent: dict, profile: dict) -> tuple[str, str]:
    fields = [("name", agent["name"]), ("description", agent["description"])]
    return f"agents/{agent['name']}.md", frontmatter(fields, agent["name"]) + "\n" + body_for(agent, True)


RENDERERS = {"claude": render_claude, "codex": render_codex, "opencode": render_opencode,
             "cursor": render_cursor, "copilot": render_copilot, "gemini": render_gemini,
             "antigravity": render_antigravity, "kiro": render_kiro}


def render_tool(tool: str, profile_name: str, out_dir: Path, agents: list[dict] | None = None,
                profile: dict | None = None) -> list[Path]:
    agents = agents if agents is not None else load_agents()
    if profile is None:
        profile = {} if profile_name == "generic" else h.load_profile(profile_name)
    written = []
    for agent in agents:
        rel, text = RENDERERS[tool](agent, profile)
        target = out_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(target)
    return written


def render_skill(source: Path, out_dir: Path) -> Path:
    """Copy a harness skill (already Agent Skills frontmatter) to <out>/<name>/SKILL.md."""
    target = out_dir / source.stem / "SKILL.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")
    return target


def render_dist(dist: Path) -> int:
    """Build harness/dist: every tool and profile combination plus the harness skills."""
    import shutil
    if dist.exists():
        shutil.rmtree(dist)
    agents = load_agents()
    count = 0
    for tool, profiles in TOOL_PROFILES.items():
        for name in profiles:
            count += len(render_tool(tool, name, dist / tool / name, agents))
    for skill in sorted((h.HARNESS_HOME / "skills").glob("*.md")):
        render_skill(skill, dist / "skills")
        count += 1
    return count


if __name__ == "__main__":
    import sys
    print(f"rendered {render_dist(Path(sys.argv[1]) if len(sys.argv) > 1 else h.HARNESS_HOME / 'dist')} files")
