class Cleaner(unittest.TestCase):
    def test_strips_claude_trailer_and_footer(self):
        msg = f"feat: x\n\nBody line.\n\n{FOOTER}\n\n{CLAUDE}\n"
        self.assertEqual(ai_trailer.clean(msg), "feat: x\n\nBody line.\n")

    def test_strips_other_tools(self):
        for line in [
            "Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
            "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
            "Co-authored-by: aider (gpt-4o) <noreply@aider.chat>",
            "Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>",
            "Assisted-by: Claude <noreply@anthropic.com>",
            "Co-authored-by: Codex <codex@openai.com>",
            "Made-with: Cursor",
            "Claude-Session: https://claude.ai/code/session_abc",
            "AI-Assisted: true",
            "Generated with ChatGPT",
        ]:
            with self.subTest(line=line):
                self.assertEqual(ai_trailer.clean(f"fix: y\n\n{line}\n"), "fix: y\n")

    def test_keeps_humans_and_prose(self):
        for msg in [
            "fix: y\n\nCo-authored-by: Claude Dupont <claude.dupont@example.org>\n",
            "fix: y\n\nSigned-off-by: Do Dang Khoa <khoa@example.org>\n",
            "fix: restore caret\n\nCreated by cursor position math in the editor.\n",
            "docs: Thai locale\n\nGenerated by the Thai build script.\n",
        ]:
            with self.subTest(msg=msg):
                self.assertEqual(ai_trailer.clean(msg), msg)

    def test_unchanged_text_is_returned_verbatim(self):
        msg = "chore: a\n\n\n\nkeep spacing\n"
        self.assertIs(ai_trailer.clean(msg), msg)


class Guard(unittest.TestCase):
    def run_guard(self, payload):
        return subprocess.run([sys.executable, str(HERE / "guard.py")], input=json.dumps(payload),
                              capture_output=True, text=True)

    def test_blocks_commit_with_trailer(self):
        cmd = f"git commit -m \"$(cat <<'EOF'\nfeat: x\n\n{CLAUDE}\nEOF\n)\""
        r = self.run_guard({"tool_name": "Bash", "tool_input": {"command": cmd}})
        self.assertEqual(r.returncode, 2, r.stderr)

    def test_blocks_trailer_flag_and_pr_body(self):
        for cmd in [f'git commit -m "x" --trailer "{CLAUDE}"',
                    f'gh pr create --title t --body "Summary\n\n{FOOTER}"']:
            with self.subTest(cmd=cmd):
                r = self.run_guard({"tool_name": "Bash", "tool_input": {"command": cmd}})
                self.assertEqual(r.returncode, 2, r.stderr)

    def test_blocks_body_file(self):
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False) as f:
            f.write(f"Summary\n\n{FOOTER}\n")
        try:
            r = self.run_guard({"tool_name": "Bash", "tool_input": {"command": f"gh pr create --body-file {f.name}"}})
            self.assertEqual(r.returncode, 2, r.stderr)
        finally:
            os.unlink(f.name)

    def test_blocks_mcp_body(self):
        r = self.run_guard({"tool_name": "mcp__github__create_pull_request",
                            "tool_input": {"title": "t", "body": f"x\n\n{FOOTER}"}})
        self.assertEqual(r.returncode, 2)

    def test_allows_clean_and_unrelated(self):
        for cmd in ['git commit -m "feat: x"', f"grep -n '{CLAUDE}' notes.md", "git log --oneline"]:
            with self.subTest(cmd=cmd):
                r = self.run_guard({"tool_name": "Bash", "tool_input": {"command": cmd}})
                self.assertEqual(r.returncode, 0, r.stderr)


@unittest.skipIf(shutil.which("git") is None, "git not installed")
class Ensure(unittest.TestCase):
    def setUp(self):
        self.home = Path(tempfile.mkdtemp())
        (self.home / ".claude").mkdir()
        (self.home / ".claude" / "settings.json").write_text(json.dumps(
            {"theme": "dark", "hooks": {"SessionStart": [{"hooks": [{"type": "command", "command": "other.sh"}]}]}}))
        vs = self.home / ".config" / "Code" / "User"
        vs.mkdir(parents=True)
        (vs / "settings.json").write_text("{}")
        (self.home / ".cursor").mkdir()
        (self.home / ".cursor" / "cli-config.json").write_text("{}")
        self.env = dict(os.environ, HOME=str(self.home), XDG_CONFIG_HOME=str(self.home / ".config"))
        self.env.pop("GIT_CONFIG_GLOBAL", None)

    def tearDown(self):
        shutil.rmtree(self.home)

    def ensure(self, *args):
        return ensure_attribution_off.main(["--home", str(self.home), "--quiet", *args])

    def test_sets_everything_and_is_idempotent(self):
        self.assertEqual(self.ensure("--check"), 1)
        self.assertEqual(self.ensure(), 0)
        self.assertEqual(self.ensure("--check"), 0)
        s = json.loads((self.home / ".claude" / "settings.json").read_text())
        self.assertEqual(s["attribution"], {"commit": "", "pr": "", "sessionUrl": False})
        self.assertEqual(s["theme"], "dark")
        self.assertEqual(len(s["hooks"]["SessionStart"]), 2)
        self.assertEqual(len(s["hooks"]["PreToolUse"]), 1)
        vs = json.loads((self.home / ".config" / "Code" / "User" / "settings.json").read_text())
        self.assertEqual(vs["git.addAICoAuthor"], "off")
        cur = json.loads((self.home / ".cursor" / "cli-config.json").read_text())
        self.assertIs(cur["attribution"]["attributeCommitsToAgent"], False)

    def test_commit_msg_hook_strips_and_chains(self):
        self.ensure()
        repo = self.home / "repo"
        subprocess.run(["git", "init", "-q", str(repo)], check=True, env=self.env)
        own = repo / ".git" / "hooks" / "post-commit"
        own.write_text("#!/bin/sh\ntouch \"$(git rev-parse --git-dir)/own-hook-ran\"\n")
        own.chmod(0o755)
        git = ["git", "-C", str(repo), "-c", "user.name=T", "-c", "user.email=t@example.org"]
        subprocess.run(git + ["commit", "-q", "--allow-empty", "-m", f"feat: x\n\n{CLAUDE}"], check=True, env=self.env)
        msg = subprocess.run(git + ["log", "-1", "--format=%B"], capture_output=True, text=True, env=self.env).stdout
        self.assertEqual(msg.strip(), "feat: x")
        self.assertTrue((repo / ".git" / "own-hook-ran").exists())

    def test_foreign_hooks_path_left_alone(self):
        subprocess.run(["git", "config", "--global", "core.hooksPath", "/elsewhere"], check=True, env=self.env)
        self.ensure()
        out = subprocess.run(["git", "config", "--global", "core.hooksPath"], capture_output=True, text=True, env=self.env)
        self.assertEqual(out.stdout.strip(), "/elsewhere")


